"""PDF со статусом ML-части для созвона команды.

    python -m ml.status_pdf

Текст и цифры вписаны руками после прогонов: скрипт ничего не пересчитывает,
чтобы в отчёт не попали случайные числа. После нового прогона править здесь.
"""
import sys

import pymupdf

from ml import paths

FONT_A = paths.font_file()
FONT_B = paths.font_file(bold=True)

W, H = 595, 842
L, R = 52, 543
TOP, BOTTOM = 62, 790

INK = (0.12, 0.13, 0.16)
MUTED = (0.42, 0.45, 0.5)
ACCENT = (0.09, 0.32, 0.62)
GOOD = (0.05, 0.45, 0.22)
WARN = (0.72, 0.28, 0.05)
RULE = (0.82, 0.84, 0.87)
BOXBG = (0.95, 0.96, 0.975)
WARNBG = (0.995, 0.955, 0.92)


class Doc:
    """Простая вёрстка сверху вниз с автоматическим переносом на новую страницу."""

    def __init__(self):
        self.doc = pymupdf.open()
        self.fa = pymupdf.Font(fontfile=FONT_A)
        self.fb = pymupdf.Font(fontfile=FONT_B)
        self.page = None
        self.y = 0
        self.n = 0
        self.new_page()

    def new_page(self):
        self.page = self.doc.new_page(width=W, height=H)
        self.page.insert_font(fontname="A", fontfile=FONT_A)
        self.page.insert_font(fontname="B", fontfile=FONT_B)
        self.y = TOP
        self.n += 1
        if self.n > 1:
            self.page.insert_text((L, H - 34), f"Инспектор ИИ - ML-часть - стр. {self.n}",
                                  fontname="A", fontsize=7.5, color=MUTED)

    def space(self, dy):
        self.y += dy

    def need(self, dy):
        if self.y + dy > BOTTOM:
            self.new_page()

    def _wrap(self, text, font, size, width):
        lines, line = [], ""
        for word in text.split(" "):
            probe = f"{line} {word}".strip()
            if font.text_length(probe, size) <= width or not line:
                line = probe
            else:
                lines.append(line)
                line = word
        if line:
            lines.append(line)
        return lines

    def text(self, s, size=9.5, bold=False, color=INK, x=L, width=None, lead=1.42, gap=5):
        font = self.fb if bold else self.fa
        width = width or (R - x)
        for line in s.split("\n"):
            for out in self._wrap(line, font, size, width):
                self.need(size * lead + 2)
                self.page.insert_text((x, self.y + size), out, fontname="B" if bold else "A",
                                      fontsize=size, color=color)
                self.y += size * lead
        self.y += gap

    def h1(self, s):
        self.need(52)
        self.space(6)
        self.text(s, size=15.5, bold=True, color=ACCENT, gap=3)
        self.page.draw_line(pymupdf.Point(L, self.y + 1), pymupdf.Point(R, self.y + 1),
                            color=RULE, width=0.9)
        self.space(11)

    def h2(self, s):
        self.need(40)
        self.space(5)
        self.text(s, size=11, bold=True, gap=4)

    def bullets(self, items, size=9.5):
        """Элемент «жирное начало|дальше обычным текстом»."""
        for it in items:
            head = ""
            if "|" in it:
                head, it = it.split("|", 1)
            self.need(size * 1.6)
            self.page.insert_text((L + 3, self.y + size), "-", fontname="A", fontsize=size, color=ACCENT)
            x = L + 13
            if head:
                self.page.insert_text((x, self.y + size), head, fontname="B", fontsize=size, color=INK)
                x += self.fb.text_length(head, size)
            first = True
            rest = it.strip()
            while rest:
                width = (R - x) if first else (R - L - 13)
                lines = self._wrap(rest, self.fa, size, width)
                self.need(size * 1.45)
                self.page.insert_text((x if first else L + 13, self.y + size), lines[0],
                                      fontname="A", fontsize=size, color=INK)
                self.y += size * 1.45
                rest = rest[len(lines[0]):].strip()
                first = False
            self.y += 1.5
        self.y += 4

    def table(self, header, rows, widths, size=8.8):
        scale = (R - L) / sum(widths)          # ширины заданы на глаз: подгоняем под поле
        widths = [w * scale for w in widths]
        self.need(30 + len(rows) * 14)
        xs, x = [], L
        for w in widths:
            xs.append(x)
            x += w
        self.page.draw_rect(pymupdf.Rect(L, self.y, L + sum(widths), self.y + 16), color=None, fill=BOXBG)
        for i, cell in enumerate(header):
            self.page.insert_text((xs[i] + 5, self.y + 11.2), cell, fontname="B", fontsize=size, color=INK)
        self.y += 16
        for row in rows:
            self.need(14)
            for i, cell in enumerate(row):
                # «+» — хорошая новость, «!» — плохая; сам знак не печатается
                color = GOOD if cell.startswith("+") else (WARN if cell.startswith("!") else INK)
                line = self._wrap(cell.lstrip("+!"), self.fa, size, widths[i] - 9)[0]
                self.page.insert_text((xs[i] + 5, self.y + 10), line, fontname="A", fontsize=size, color=color)
            self.page.draw_line(pymupdf.Point(L, self.y + 14), pymupdf.Point(L + sum(widths), self.y + 14),
                                color=RULE, width=0.5)
            self.y += 14
        self.y += 9

    def box(self, title, body, warn=False):
        size = 9.5
        lines = []
        for para in body.split("\n"):
            lines += self._wrap(para, self.fa, size, R - L - 28)
        hgt = 26 + len(lines) * size * 1.45 + 8
        self.need(hgt + 6)
        self.page.draw_rect(pymupdf.Rect(L, self.y, R, self.y + hgt), color=None,
                            fill=WARNBG if warn else BOXBG)
        self.page.draw_line(pymupdf.Point(L, self.y), pymupdf.Point(L, self.y + hgt),
                            color=WARN if warn else ACCENT, width=2.5)
        self.page.insert_text((L + 14, self.y + 17), title, fontname="B", fontsize=10,
                              color=WARN if warn else ACCENT)
        yy = self.y + 26
        for line in lines:
            self.page.insert_text((L + 14, yy + size), line, fontname="A", fontsize=size, color=INK)
            yy += size * 1.45
        self.y += hgt + 12

    def flow(self, steps):
        """Схема: блоки сверху вниз со стрелками. Шаг — (название, чем делается, состояние)."""
        bh, gap = 38, 12
        self.need(len(steps) * (bh + gap) + 10)
        name_w = 150
        for i, (name, how, state) in enumerate(steps):
            y0 = self.y
            rect = pymupdf.Rect(L, y0, R, y0 + bh)
            self.page.draw_rect(rect, color=RULE, fill=BOXBG, width=0.8)
            self.page.draw_rect(pymupdf.Rect(L, y0, L + 4, y0 + bh), color=None,
                                fill=GOOD if state == "ok" else WARN)
            self.page.insert_text((L + 12, y0 + 15), f"{i}. {name}", fontname="B", fontsize=9.5, color=INK)
            self.page.insert_text((L + 12, y0 + 29), "готово" if state == "ok" else "частично",
                                  fontname="A", fontsize=7.8, color=GOOD if state == "ok" else WARN)
            lines = self._wrap(how, self.fa, 8.6, R - L - name_w - 16)
            ty = y0 + (bh - len(lines) * 11.5) / 2 + 9
            for line in lines[:3]:
                self.page.insert_text((L + name_w, ty), line, fontname="A", fontsize=8.6, color=INK)
                ty += 11.5
            self.y = y0 + bh
            if i < len(steps) - 1:
                cx = (L + R) / 2
                self.page.draw_line(pymupdf.Point(cx, self.y + 1), pymupdf.Point(cx, self.y + gap - 2),
                                    color=ACCENT, width=1.2)
                self.page.draw_polyline([pymupdf.Point(cx - 3.5, self.y + gap - 5), pymupdf.Point(cx, self.y + gap - 1),
                                         pymupdf.Point(cx + 3.5, self.y + gap - 5)], color=ACCENT, width=1.2)
            self.y += gap
        self.y += 4

    def save(self, path):
        self.doc.save(path, garbage=3, deflate=True)
        return self.doc.page_count


