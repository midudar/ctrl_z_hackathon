T = {k: [re.compile(x, I) for x in v] for k, v in T.items()}


def main():
    man = [r for r in paths.read_jsonl(paths.MANIFEST) if r["object_id"] == OBJ and r.get("extension", ".pdf").lower() == ".pdf"
           or (r["object_id"] == OBJ and str(r.get("relative_path", "")).lower().endswith(".pdf"))]
    hits = {k: {"PD": [], "RD": []} for k in T}
    pages = {"PD": 0, "RD": 0}
    for stage, sts in (("PD", {"PD"}), ("RD", {"RD", "RD_ID_MIXED"})):
        rows, _ = revisions.latest([r for r in man if r["stage"] in sts])
        for r in rows:
            try:
                doc = pymupdf.open(file_path(r["file_id"]))
            except Exception:
                continue
            for pno, page in enumerate(doc, 1):
                pages[stage] += 1
                try:
                    text = page.get_text()
                except Exception:
                    continue
                for line in text.splitlines():
                    for k, rxs in T.items():
                        if all(rx.search(line) for rx in rxs):
                            hits[k][stage].append((r["file_id"], pno, r.get("section"), " ".join(line.split())[:110]))
    print(f"{OBJ}: страниц ПД {pages['PD']}, РД {pages['RD']}")
    summary = {}
    for k, h in hits.items():
        pdf, rdf = sorted({x[0] for x in h["PD"]}), sorted({x[0] for x in h["RD"]})
        summary[k] = {"pd_lines": len(h["PD"]), "rd_lines": len(h["RD"]), "pd_files": pdf, "rd_files": rdf,
                      "pd_ex": h["PD"][:6], "rd_ex": h["RD"][:6]}
        mark = "ОБЕ" if h["PD"] and h["RD"] else "   "
        print(f"{mark} {k:38} ПД {len(h['PD']):5} стр. в {len(pdf):3} ф. | РД {len(h['RD']):5} стр. в {len(rdf):3} ф.")
    if OUT:
        json.dump(summary, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
